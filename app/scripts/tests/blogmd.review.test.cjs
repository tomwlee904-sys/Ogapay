// Every case the reviewers confirmed, plus speed checks
const { renderBlog: r } = require('./load-blogmd.cjs');
let fails = 0;
const ok = (name, cond, got) => { console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '\n   got: ' + String(got).slice(0, 400))); if (!cond) fails++; };
const A = (href, text) => `<a href="${href}" target="_blank" rel="noopener nofollow ugc">${text ?? href}</a>`;
const BS = String.fromCharCode(92);
let h;

h = r('Price **₦5,000** at https://ogapay.app/store/item_*1*');
ok('a * at the end of a link stays outside it, no italics inside the address', h.includes(A('https://ogapay.app/store/item_*1')) && !/href="[^"]*<em>/.test(h), h);
h = r('**Register here: https://ogapay.app/r/tunde12**');
ok('bold around a link', h === `<p><strong>Register here: ${A('https://ogapay.app/r/tunde12')}</strong></p>`, h);
h = r('*see https://ogapay.app*');
ok('italics around a link', h === `<p><em>see ${A('https://ogapay.app')}</em></p>`, h);
h = r('~~https://old.ogapay.app~~');
ok('strike-through around a link', h === `<p><del>${A('https://old.ogapay.app')}</del></p>`, h);
h = r('[`npm install`](https://docs.npmjs.com)');
ok('code inside link text is kept', h === `<p>${A('https://docs.npmjs.com', '<code>npm install</code>')}</p>`, h);
h = r('Read the "`npm` guide" (https://docs.npmjs.com)');
ok('code inside a "Name" (link)', h === `<p>Read the ${A('https://docs.npmjs.com', '<code>npm</code> guide')}</p>`, h);
h = r('https://ogapay.app`code`');
ok('code right after a link', h === `<p>${A('https://ogapay.app')}<code>code</code></p>`, h);
ok('no hidden markers left anywhere', ![h, r('[`a`](https://b.co) and "`c`" (https://d.co) https://e.co`f`')].some((x) => x.includes('\u0000')), 'marker found');
h = r('Join here https://t.me/ogapayhq🔥🔥');
ok('emoji after a link stays outside it', h === `<p>Join here ${A('https://t.me/ogapayhq')}🔥🔥</p>`, h);
h = r('Register👉https://ogapay.app/r/abc123👈🏽');
ok('emoji on both sides', h === `<p>Register👉${A('https://ogapay.app/r/abc123')}👈🏽</p>`, h);
h = r('“https://ogapay.app”');
ok('curly quotes around a link', h === `<p>“${A('https://ogapay.app')}”</p>`, h);
h = r('Read the “OgaPay FAQ” (https://ogapay.app/faq) first.');
ok('“Name” (link) with phone-keyboard quotes', h === `<p>Read the ${A('https://ogapay.app/faq', 'OgaPay FAQ')} first.</p>`, h);
h = r('[Link: https://ogapay.app]');
ok('a ] after a link stays outside it', h === `<p>[Link: ${A('https://ogapay.app')}]</p>`, h);
h = r('Open https://ogapay.app… then sign up');
ok('… after a link', h === `<p>Open ${A('https://ogapay.app')}… then sign up</p>`, h);
h = r('https://ogapay.app—the best');
ok('em dash after a link', h === `<p>${A('https://ogapay.app')}—the best</p>`, h);
h = r('[https://good.com](http://bad.com)');
ok('an http:// markdown target is never linked', !h.includes('http://bad.com"') && !h.includes('href="http:'), h);
h = r('Form: https://docs.google.com/forms/viewform?usp=sf_link&');
ok('a link ending in & keeps it, no stray ;', h === `<p>Form: ${A('https://docs.google.com/forms/viewform?usp=sf_link&amp;')}</p>`, h);
h = r("https://en.wikipedia.org/wiki/People's_Democratic_Party_(Nigeria)");
ok('apostrophe and (brackets) inside a link', h === `<p>${A('https://en.wikipedia.org/wiki/People&#039;s_Democratic_Party_(Nigeria)')}</p>`, h);
h = r("'https://ogapay.app/jobs'");
ok('single quotes around a link', h === `<p>&#039;${A('https://ogapay.app/jobs')}&#039;</p>`, h);
h = r('(see https://ogapay.app/faq)');
ok('a closing bracket after a link', h === `<p>(see ${A('https://ogapay.app/faq')})</p>`, h);
h = r('Links must start with https://. Paste a link like https://... in the box');
ok('"https://" on its own is not linked', !h.includes('<a '), h);
h = r('[Click](/' + BS + 'evil.com)');
ok('a backslash link is not treated as a site link', !h.includes('<a '), h);
h = r('![x](/' + BS + 'evil.com/pixel.png)');
ok('a backslash picture is not shown', !h.includes('<img'), h);
h = r('https://evil.com/' + BS + 'x');
ok('a backslash ends a pasted address', !/href="[^"]*\x5c/.test(h), h);
h = r('[ok](/blog/post) ![p](/img/a.png) [ext](https://ogapay.app)');
ok('normal site links and pictures still work', h.includes('<a href="/blog/post">ok</a>') && h.includes(A('https://ogapay.app', 'ext')), h);

const time = (input) => { const t = Date.now(); r(input); return Date.now() - t; };
const t1 = time('https://a.com/' + ')'.repeat(49986));
ok(`50,000 ")" after a link is quick (${t1} ms)`, t1 < 200, t1);
const t2 = time('https://a' + '.)'.repeat(25000));
ok(`".)" x 25,000 is quick (${t2} ms)`, t2 < 200, t2);
const t3 = time(Array.from({ length: 25 }, () => 'https://a.com/' + ')'.repeat(20000)).join('\n'));
ok(`25 long lines is quick (${t3} ms)`, t3 < 500, t3);
const t4 = time(('Visit https://ogapay.app/tasks?x=1&y=2 and "FAQ" (https://ogapay.app/faq) **now** ').repeat(2000));
ok(`a long realistic article is quick (${t4} ms)`, t4 < 500, t4);
const t5 = time('https://' + 'a('.repeat(20000));
ok(`unclosed brackets are quick (${t5} ms)`, t5 < 500, t5);
const t6 = time('"' + 'x'.repeat(150) + '" ('.repeat(3000));
ok(`many quotes and brackets are quick (${t6} ms)`, t6 < 500, t6);

console.log(fails ? `\n${fails} FAILED` : '\nALL PASSED'); process.exit(fails ? 1 : 0);
