// Blog text renderer (src/lib/blogMarkdown.ts): links, formatting and safety.
//   npm run test:blog-links
const { renderBlog: r } = require('./load-blogmd.cjs');
let fails = 0;
const ok = (name, cond, got) => { console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '\n   got: ' + got)); if (!cond) fails++; };
const A = (href, text) => `<a href="${href}" target="_blank" rel="noopener nofollow ugc">${text}</a>`;
let h;
h = r('Read the "OgaPay FAQ" (https://ogapay.app/faq) first.');
ok('Faith style "Name" (link) becomes a named link', h === `<p>Read the ${A('https://ogapay.app/faq', 'OgaPay FAQ')} first.</p>`, h);
h = r('See https://ogapay.app/tasks.');
ok('a pasted link is linked, the full stop stays outside', h === `<p>See ${A('https://ogapay.app/tasks', 'https://ogapay.app/tasks')}.</p>`, h);
h = r('(source: https://example.com/a_(b))');
ok('brackets: inner pair kept, closing bracket of the sentence left out', h === `<p>(source: ${A('https://example.com/a_(b)', 'https://example.com/a_(b)')})</p>`, h);
h = r('Go to https://x.com/search?q=a&b=c now');
ok('& in a link works (escaped once in href and text)', h === `<p>Go to ${A('https://x.com/search?q=a&amp;b=c', 'https://x.com/search?q=a&amp;b=c')} now</p>`, h);
h = r('[OgaPay](https://ogapay.app) and https://ogapay.app');
ok('markdown links still work and are not linked twice', h === `<p>${A('https://ogapay.app', 'OgaPay')} and ${A('https://ogapay.app', 'https://ogapay.app')}</p>`, h);
h = r('[**Bold** link](https://ogapay.app)');
ok('formatting inside link text still works', h === `<p>${A('https://ogapay.app', '<strong>Bold</strong> link')}</p>`, h);
h = r('[Tasks](/tasks)');
ok('site links still open in the same tab', h === '<p><a href="/tasks">Tasks</a></p>', h);
h = r('Use `https://ogapay.app/api` in code');
ok('links inside `code` stay plain code', h === '<p>Use <code>https://ogapay.app/api</code> in code</p>', h);
h = r('Not http://insecure.com or javascript:alert(1)');
ok('http:// and javascript: are never linked', h === '<p>Not http://insecure.com or javascript:alert(1)</p>', h);
h = r('https://evil.com/"onmouseover="alert(1)');
ok('a quote can\'t break out of the link', !/onmouseover="/.test(h) && h.includes('href="https://evil.com/"'), h);
h = r('https://evil.com/<script>alert(1)</script>');
ok('no tags get through', !/<script/i.test(h), h);
h = r('"x" (javascript:alert(1)) and "y" (http://a.com)');
ok('"Name" (link) only accepts https', !/<a /.test(h), h);
h = r('Price **₦5,000** at https://ogapay.app/store/item_*1*');
ok('* at the end of a link stays outside it', h.includes('href="https://ogapay.app/store/item_*1"') && !/href="[^"]*<em>/.test(h), h);
h = r('- Source: "SEC notice" (https://home.sec.gov.ng/notice/)');
ok('links in list items', h === `<ul><li>Source: ${A('https://home.sec.gov.ng/notice/', 'SEC notice')}</li></ul>`, h);
h = r('| Site | Link |\n| --- | --- |\n| OgaPay | https://ogapay.app |');
ok('links in tables', h.includes(A('https://ogapay.app', 'https://ogapay.app')), h);
h = r('![A picture](https://ogapay.app/a.png)');
ok('pictures unchanged', h === '<figure><img src="https://ogapay.app/a.png" alt="A picture" loading="lazy" decoding="async" /><figcaption>A picture</figcaption></figure>', h);
h = r('Weird \u00000\u0000 text');
ok('the internal marker can\'t be faked', !h.includes('\u0000') && !/<a /.test(h), h);
h = r('Plain **bold** and *italic* ~~old~~');
ok('ordinary formatting unchanged', h === '<p>Plain <strong>bold</strong> and <em>italic</em> <del>old</del></p>', h);
console.log(fails ? `\n${fails} FAILED` : '\nALL PASSED'); process.exit(fails ? 1 : 0);
